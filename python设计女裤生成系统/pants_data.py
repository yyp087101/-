def get_pants_data(pants_type, zuo_gao=None, yao_gao=None, yao_wei=None, tun_wei=None):
                                     
    if pants_type not in PANTS_DB:
        raise ValueError(f"未知裤型: {pants_type}")
    style = copy.deepcopy(PANTS_DB[pants_type])
    std = style["std_input"]

    zuo_gao = zuo_gao if zuo_gao is not None else std["坐高"]
    yao_gao = yao_gao if yao_gao is not None else std["腰高"]
    yao_wei = yao_wei if yao_wei is not None else std["腰围"]
    tun_wei = tun_wei if tun_wei is not None else std["臀围"]

                                    
    if pants_type == "女西裤":
        data = calculate_pants_legacy(pants_type, yao_wei, tun_wei, yao_gao, zuo_gao)
    else:
        data = calculate_pants_doc(pants_type, yao_wei, tun_wei, yao_gao, zuo_gao)
    data["name"] = style.get("name", pants_type)
    data["filename"] = style.get("filename", pants_type)
    data["std_input"] = style["std_input"]
    if "draw_mode" in style and "draw_mode" not in data:
        data["draw_mode"] = style["draw_mode"]
                                  
    data.setdefault("front_dart", [])
    data.setdefault("back_dart", [])
    return data
